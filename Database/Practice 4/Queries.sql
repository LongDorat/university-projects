-- 17
SELECT COUNT(*)
FROM (
    SELECT HOTEN_KTS
    FROM THIETKE
    GROUP BY HOTEN_KTS
    HAVING SUM(THU_LAO) > 25
)  AS SO_LUONG_KTS;

-- 18
SELECT HOTEN_KTS, SUM(STT_CTR) AS SO_LUONG_CTR
FROM THIETKE
GROUP BY HOTEN_KTS;

-- 19
SELECT _cgTrinh.TEN_CTR, COUNT(_thamGia.HOTEN_CN) AS SO_LUONG_CN
FROM CGTRINH _cgTrinh
    LEFT JOIN THAMGIA _thamGia ON _cgTrinh.STT_CTR = _thamGia.STT_CTR
GROUP BY _cgTrinh.STT_CTR, _cgTrinh.TEN_CTR;

--20
SELECT _cgTrinh.TEN_CTR, _cgTrinh.DIACHI_CTR
FROM CGTRINH _cgTrinh
    JOIN (
    SELECT STT_CTR, COUNT(HOTEN_CN) AS SO_LUONG_CN
    FROM THAMGIA
    GROUP BY STT_CTR
) _soLuongCn ON _cgTrinh.STT_CTR = _soLuongCn.STT_CTR
WHERE _soLuongCn.SO_LUONG_CN = (
    SELECT MAX(SO_LUONG_CN)
FROM (
    SELECT COUNT(HOTEN_CN) AS SO_LUONG_CN
    FROM THAMGIA
    GROUP BY STT_CTR
    ) SO_LUONG_CN_MAX
);

