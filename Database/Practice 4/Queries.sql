FROM CONGNHAN _congNhan
    JOIN THAMGIA _thamGia ON _congNhan.HOTEN_CN = _thamGia.HOTEN_CN
    JOIN CGTRINH _cgTrinh ON _cgTrinh.STT_CTR = _thamGia.STT_CTR
WHERE _congNhan.CH_MON IN ('han', 'dien') AND _cgTrinh.TEN_THAU = 'le van son';

-- 9
SELECT _congNhan.*
FROM CONGNHAN _congNhan
    JOIN THAMGIA _thamGia ON _congNhan.HOTEN_CN = _thamGia.HOTEN_CN
    JOIN CGTRINH _cgTrinh ON _cgTrinh.STT_CTR = _thamGia.STT_CTR
WHERE _cgTrinh.TINH_THANH = 'can tho'
    AND _cgTrinh.TEN_CTR = 'khach san quoc te'
    AND _thamGia.NGAY_TGIA BETWEEN '1994-12-15' AND '1994-12-31';

